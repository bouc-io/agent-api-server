/**
 * LLM Type Definitions
 * Common interfaces for LLM client interactions
 */

/**
 * Message format for LLM conversations
 */
export interface LLMMessage {
  role: "system" | "user" | "assistant" | "tool";
  content: string;
  tool_call_id?: string;
  tool_calls?: LLMToolCall[];
}

/**
 * Tool definition in LLM-compatible format
 */
export interface LLMToolDefinition {
  type: "function";
  function: {
    name: string;
    description: string;
    parameters: Record<string, unknown>;
  };
}

/**
 * Tool call returned by LLM
 */
export interface LLMToolCall {
  id: string;
  name: string;
  arguments: Record<string, unknown>;
}

/**
 * LLM response structure
 */
export interface LLMResponse {
  content?: string;
  tool_calls?: LLMToolCall[];
  finish_reason: "stop" | "tool_calls" | "length";
  usage?: {
    prompt_tokens: number;
    completion_tokens: number;
  };
}

/**
 * Accumulated token usage across multiple LLM calls within a single run phase
 */
export interface TokenAccumulator {
  prompt_tokens: number;
  completion_tokens: number;
  total_tokens: number;
  llm_calls: number;
}

/** Create a zeroed token accumulator */
export function createTokenAccumulator(): TokenAccumulator {
  return {
    prompt_tokens: 0,
    completion_tokens: 0,
    total_tokens: 0,
    llm_calls: 0,
  };
}

/**
 * Add a single LLMResponse.usage into an accumulator (mutates in place).
 * Increments llm_calls unconditionally; adds tokens only if usage is present.
 */
export function accumulateTokens(
  acc: TokenAccumulator,
  usage?: { prompt_tokens: number; completion_tokens: number },
): void {
  acc.llm_calls += 1;
  if (usage) {
    acc.prompt_tokens += usage.prompt_tokens;
    acc.completion_tokens += usage.completion_tokens;
    acc.total_tokens += usage.prompt_tokens + usage.completion_tokens;
  }
}

/**
 * Options for LLM chat calls
 */
export interface LLMChatOptions {
  tools?: LLMToolDefinition[];
  temperature?: number;
  max_tokens?: number;
  /** Ollama 0.7+ top-level think parameter. Pass false to suppress chain-of-thought
   *  at the model level — more reliable than the /no_think text directive alone. */
  think?: boolean;
}

/**
 * Streaming callbacks passed to LLMClient.chatStream().
 * - onToken: regular response token (accumulated into the full response by the caller)
 * - onThinkingToken: chain-of-thought token (streamed to the UI but not stored directly)
 * - onDone: signals end of stream; includes token usage and optionally the full thinking
 *   content (JSON-format only) so the caller can reconstruct the <think>…</think> block
 *   for storage without re-accumulating from onThinkingToken.
 * - onError: fatal streaming error
 *
 * Carried over from chatbot-api-server with the /v1/chats surface. The onDone.thinking
 * contract is load-bearing: the chat UI parses <think>…</think> back out of stored
 * message content, so only JSON-format thinking is reported here (legacy <think>-tag
 * thinking is streamed to the client but never stored).
 */
export interface LLMStreamCallbacks {
  onToken: (token: string) => void;
  onThinkingToken?: (token: string) => void;
  onDone?: (usage: {
    prompt_tokens: number;
    completion_tokens: number;
    /** Accumulated thinking content (JSON-format only). Used to rebuild finalContent. */
    thinking?: string;
  }) => void;
  onError?: (err: Error) => void;
}

/**
 * LLM client interface
 *
 * chatStream is optional: the agentic path only ever calls chat(), and leaving it
 * optional means a future client can ship without a streaming implementation. Call
 * sites that need streaming narrow with isStreamingClient() first.
 */
export interface LLMClient {
  chat(messages: LLMMessage[], options?: LLMChatOptions): Promise<LLMResponse>;
  chatStream?(
    messages: LLMMessage[],
    callbacks: LLMStreamCallbacks,
    options?: LLMChatOptions,
  ): Promise<void>;
}

/** An LLMClient that is known to support token streaming. */
export interface StreamingLLMClient extends LLMClient {
  chatStream(
    messages: LLMMessage[],
    callbacks: LLMStreamCallbacks,
    options?: LLMChatOptions,
  ): Promise<void>;
}

/** Narrow an LLMClient to one that can stream. */
export function isStreamingClient(
  client: LLMClient,
): client is StreamingLLMClient {
  return typeof (client as StreamingLLMClient).chatStream === "function";
}

/**
 * Plan structure generated by Planner phase
 */
export interface Plan {
  goal: string;
  steps: PlanStep[];
}

/**
 * Individual step in a plan
 */
export interface PlanStep {
  id: number;
  description: string;
  tool_intent: string | null;
}
